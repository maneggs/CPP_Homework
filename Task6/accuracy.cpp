#include <iostream>

int main()
{

    double a = 0.1;
    double b = 0.2;
    double sum = a + b;

    // В памяти компьютера числа 0.1 и 0.2 в двоичной системе являются бесконечными дробями
    // При сложении возникает крошечная погрешность (0.30000000000000004)
    // при выводе cout округляет число до 6 значащих цифр, поэтому 0.3
    std::cout << "Сумма: " << sum << std::endl;

    // Оператор == сравнивает числа в памяти бит в бит без округления.
    // Так как 0.30000000000000004 не равно точному 0.3, результат сравнения false (0).
    std::cout << "Сумма равна 0.3? " << (sum == 0.3) << std::endl;

    // По умолчанию cout выводит 6 значащих цифр.
    // Остальной хвост скрывается стандартным округлением вывода
    std::cout << "Треть: " << (1.0 / 3.0) << std::endl;

    return 0;
}
